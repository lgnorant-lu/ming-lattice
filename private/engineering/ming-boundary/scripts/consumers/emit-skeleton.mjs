#!/usr/bin/env node
// emit-skeleton（内置目录件, outputs=files, mutates=true, phases=[manual]）
// 从观察拓扑起草 boundaries.suggested.yaml——纯推断稿, 人工审后才准转正
// terraform -generate-config-out 同款防线:
//   目标已存在 → 拒写(fail-closed); 无 --apply → 只报 planned; 降级面大 → 头部警示
// argv: --facts F --root R --config JSON [--apply]
import fs from 'node:fs';
import path from 'node:path';
import { parseJsonl, globMatch } from '../lib/facts.mjs';

const argv = process.argv;
const take = (k) => argv[argv.indexOf(k) + 1];
const factsPath = take('--facts');
const root = path.resolve(take('--root'));
const cfg = JSON.parse(take('--config') || '{}');
const apply = argv.includes('--apply');
const outRel = cfg.out || 'boundaries.suggested.yaml';
const outPath = path.resolve(root, outRel);
const die = (m) => { console.error(`[emit-skeleton] ${m}`); process.exit(2); };
if (!outPath.startsWith(root + path.sep)) die(`out 越出仓根: ${outRel}`);
if (fs.existsSync(outPath)) die(`目标已存在, 拒覆盖: ${outRel}`);

const facts = parseJsonl(fs.readFileSync(factsPath, 'utf8'));
const fileFacts = facts.filter(f => f.kind === 'file');
const degr = new Set(facts.filter(f => f.fidelity === 'regex-degraded' && f.extractor === 'line-regex@1')
  .map(f => f.unit.split('#')[0]));

// 顶层目录画像
const top = new Map();
for (const f of fileFacts) {
  const seg = String(f.unit).replace(/\\/g, '/').split('/');
  if (seg.length > 1) top.set(seg[0], (top.get(seg[0]) || 0) + 1);
}
const dirs = [...top.entries()].sort((a, b) => b[1] - a[1]);
const has = (re) => dirs.some(([d]) => re.test(d));
// 顶层目录是否被 gitignore 声明=比率判定：dir 下 ≥80% 文件带 declare 边才算忽略
// （首段截断会误伤：deployable/x/.claude 这类点文件命中不该污染整目录判定）
const declaredFiles = new Set(facts.filter(f => f.kind === 'declare')
  .map(f => String(f.extra?.to || '').replace(/\/$/, '')).filter(Boolean));
const dirDeclared = new Map();
for (const f of fileFacts) {
  const d = String(f.unit).split('/')[0];
  if (!top.has(d)) continue;
  if (declaredFiles.has(f.unit)) dirDeclared.set(d, (dirDeclared.get(d) || 0) + 1);
}
const ignoredDirs = new Set([...top.keys()].filter(d =>
  (dirDeclared.get(d) || 0) / top.get(d) >= 0.8));

const L = [];
L.push(`# generated by emit-skeleton from OBSERVED topology — REVIEW REQUIRED`);
L.push(`# facts=${facts.length} files=${fileFacts.length} degraded=${degr.size}` +
  (degr.size / Math.max(1, fileFacts.size || fileFacts.length) > 0.2
    ? '  [WARN] 降级面>20%, 推断可信度低' : ''));
L.push(`# 推断规则一律 level:warn——确认后再升 error。生成时间: ${new Date().toISOString()}`);
L.push(`version: 1`);
L.push(`domains:`);
for (const [d, c] of dirs) {
  if (ignoredDirs.has(d))
    { L.push(`  # - name: '${d}'   # files=${c} [gitignored——注释态, 启用请删 #]`); continue; }
  L.push(`  - name: '${d}'`, `    match: '${d}/**'   # files=${c}`);
}
L.push(`  - name: 'root'`, `    match: '*'   # 根层散件`);
L.push(`manifest:`);
L.push(`  node_kinds: [file, dir, decl]`);
L.push(`  edge_kinds: [import, link, docref, mention, declare, export]`);
L.push(`  families: [forbidden, allowed, required, covered, isolated, parity, attrs]`);
L.push(`  extractors: [walk, 'ast-grep', 'line-regex', markdown, 'git-check-ignore']`);
L.push(`  find_levels: [error, warn, note]`);
L.push(`rules:`);
L.push(`  attrs:`);
L.push(`    - name: no-debris-at-root`);
L.push(`      units_in: '*'`);
L.push(`      name_not_match: ['*.tmp', '*.bak', '*.log', '*.profraw', '*.dmp', 'probe_*.*', '*-dump.*']`);
L.push(`      severity: warn   # inferred`);
L.push(`      why: 'inferred: 根层散件常态为残骸——确认或删'`);
if (has(/^(docs?|wiki|documentation|guides?)$/i)) {
  const d = dirs.find(([x]) => /^(docs?|wiki|documentation|guides?)$/i.test(x))[0];
  // 预评估：units_in 命中的 md 单元里多少篇零 docref 入度——写进注释防告警疲劳
  const pat = `${d}/**/*.md`;
  const inbound = new Set(facts.filter(f => f.kind === 'docref')
    .map(f => f.extra?.to).filter(Boolean));
  const uncovered = fileFacts
    .filter(f => globMatch(f.unit, pat) && !inbound.has(f.unit)).length;
  L.push(`  covered:`);
  L.push(`    - name: docs-covered`);
  L.push(`      units_in: '${pat}'`);
  L.push(`      needs: [docref]`);
  L.push(`      severity: warn   # inferred`);
  L.push(`      why: 'inferred: 存在 ${d}/ 文档目录——孤儿文档检测'`);
  L.push(`      # 现状: ${uncovered} 篇零入度——量大可先收窄 units_in（如 '${d}/*.md' 仅顶层）`);
}
const vend = dirs.find(([d]) => /^(vendor|vendored|third_party|_ref|deps)$/i.test(d));
if (vend && has(/^tests?$/i)) {
  const vendDom = vend[0], live = !ignoredDirs.has(vendDom);
  if (!live) {
    L.push(`  # forbidden:`);
    L.push(`  #   - name: test-never-imports-vendor`);
    L.push(`  #     from: 'tests'`);
    L.push(`  #     to: '${vendDom}'`);
    L.push(`  #     via: [import]`);
    L.push(`  #   —— ${vendDom}/ 被 gitignore（注释态域），规则暂不可评；启用域后解开`);
  } else {
    L.push(`  forbidden:`);
    L.push(`    - name: test-never-imports-vendor`);
    L.push(`      from: 'tests'`);
    L.push(`      to: '${vendDom}'`);
    L.push(`      via: [import]`);
    L.push(`      severity: warn   # inferred`);
    L.push(`      why: 'inferred: 检出 vendored 目录 ${vendDom} 与 tests/ 共存'`);
  }
}
if (ignoredDirs.size) {
  L.push(`  # 检出被忽略顶层目录（gitignore declare）: ${[...ignoredDirs].slice(0, 12).join(', ')}`);
  L.push(`  # 其内容事实已被剪枝——如需"禁止被引用"再按需加 isolated`);
}
L.push(``);

const body = L.join('\n');
if (!apply) { console.log(JSON.stringify({ planned: [outRel], preview: body })); process.exit(0); }
fs.writeFileSync(outPath, body, 'utf8');
console.log(JSON.stringify({ planned: [outRel], written: [outRel] }));
